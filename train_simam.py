# train_simam.py
# 改进模型训练脚本（YOLOv8n-SimAM）
from pathlib import Path  # 导入路径处理模块
from ultralytics import YOLO  # 导入Ultralytics YOLO库，用于模型加载和训练

ROOT = Path(__file__).resolve().parent  # 仓库根目录（即本脚本所在目录）

print("=" * 60)
print(" 改进模型训练（YOLOv8n-SimAM，与基线模型公平对比）")
print("=" * 60)

# 关键改进：从COCO预训练权重加载，再应用SimAM配置
# 这样确保改进模型与基线模型具有相同的初始化条件
model = YOLO('yolov8n.pt')  # 先加载预训练权重（COCO数据集预训练，参数量3.2M）
# 再加载带SimAM的配置文件，并将预训练权重迁移到新模型结构中
model = YOLO(str(ROOT / 'yolov8n_simam_middle.yaml')).load('yolov8n.pt')

# 改进后的训练参数
results = model.train(
    data=str(ROOT / 'dataset.yaml'),
    epochs=150,
    batch=4,  # 批次大小：每次梯度更新使用4张图像（受限于CPU内存）
    imgsz=640, # 输入图像尺寸：将图像缩放为640×640像素
    device='cpu',
    workers=0, # 数据加载线程数：Windows下设为0避免多进程问题

    # ========== 新增：几何变换（针对所有缺陷优化）==========
    degrees=45,  # 旋转角度：正负45度范围内随机旋转，让模型学习各个方向的缺陷
    scale=0.5,  # 缩放幅度：图像尺寸在0.5-1.5倍之间随机缩放，适应不同尺寸缺陷
    shear=15,  # 剪切变换：正负15度范围内随机剪切，模拟缺陷形变
    translate=0.1,  # 平移：正负10%范围内随机平移，使缺陷位置多样化
    fliplr=0.5,  # 水平翻转概率：50%概率随机左右翻转，增加镜像样本
    flipud=0.3,  # 垂直翻转概率：30%概率随机上下翻转，增强样本多样性
    # ====================================================

    # ========== 色彩变换（配合几何变换使用）==========
    hsv_h=0.02,  # 色调变化幅度：随机调整色调，模拟光源色温差异
    hsv_s=0.8,  # 饱和度变化幅度：随机调整饱和度，增强对比度鲁棒性
    hsv_v=0.4,  # 明度变化幅度：随机调整明度，模拟光照强度波动
    # ====================================================

    # 学习率设置
    lr0=0.0005,  # 初始学习率：参数更新的初始步长（较小值保证训练稳定）
    lrf=0.0005,   # 最终学习率：训练结束时的学习率（与初始相同，保持恒定）学习率在整个训练过程中保持不变，始终为 0.0005。
                #学习率在整个训练过程中保持不变，始终为 0.0005。稳定但慢，不容易错过目标
    warmup_epochs=5,  # 预热轮数：前5轮学习率从较小值线性增长到初始学习率
    warmup_momentum=0.8,  # 预热动量：预热阶段的动量参数
    warmup_bias_lr=0.05,  # 预热偏置学习率：预热阶段偏置参数的学习率

    # 优化器设置
    optimizer='AdamW',
    momentum=0.937,  # 动量参数：加速梯度下降，抑制参数更新震荡（YOLO推荐值）
    weight_decay=0.0005,  # 权重衰减：L2正则化系数，防止过拟合
    # 损失权重（可选，提高分类权重）
    cls=0.8,  # 分类损失权重：提高至0.8（默认0.5），增强模型对缺陷类别的判别能力
    box=7.5,  # 边界框损失权重：保持默认值7.5，控制定位精度
    dfl=1.5,  # 分布焦点损失权重：保持默认值1.5，优化边界框分布

    # 早停设置
    patience=50,   # 早停耐心值：验证集mAP50连续50轮未提升则停止训练，防止过拟合

    # 保存设置
    name='scratch_with_simam_v2',
    exist_ok=True,  # 允许覆盖已存在的同名文件夹
    verbose=True  # 打印详细训练日志
)

print(" 训练完成！")
